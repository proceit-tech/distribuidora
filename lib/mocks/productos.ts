function slug(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "sin-clasificar";
}

function paisCodigo(procedencia: string) {
  const value = procedencia.toUpperCase();

  if (value.includes("FRANCIA")) {
    return "FRA";
  }

  if (value.includes("ITALIA")) {
    return "ITA";
  }

  if (value.includes("ESPAÑA")) {
    return "ESP";
  }

  if (value.includes("NAINJING")) {
    return "CHN";
  }

  return "";
}

function paisNombre(procedencia: string) {
  const code = paisCodigo(procedencia);

  if (code === "FRA") {
    return "Francia";
  }

  if (code === "ITA") {
    return "Italia";
  }

  if (code === "ESP") {
    return "España";
  }

  if (code === "CHN") {
    return "China";
  }

  return procedencia;
}

function buildCatalog(
  index: 2 | 3 | 4,
  prefix: string,
): ProductoCatalogoOpcion[] {
  const values = Array.from(
    new Set(
      INVENTARIO_MINGO
        .map((row) => row[index])
        .filter(Boolean),
    ),
  ).sort((a, b) => a.localeCompare(b));

  return values.map((nombre) => ({
    id: `${prefix}-${slug(nombre)}`,
    codigo: slug(nombre).toUpperCase(),
    nombre,
  }));
}

